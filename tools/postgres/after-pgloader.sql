-- Run on a PostgreSQL database populated by pgloader, never on SQL Server.
-- The application uses DateTimeOffset for these columns. A prior run of this
-- script may have converted them; restore timestamptz before fixing DateTime.
DO $migration$
DECLARE
    column_to_fix record;
BEGIN
    FOR column_to_fix IN
        SELECT table_name, column_name
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND data_type = 'timestamp without time zone'
          AND (table_name, column_name) IN (
              VALUES ('tbCarteira', 'CriadaEm'),
                     ('tbCarteira', 'AtualizadaEm'),
                     ('tbPluggyConnection', 'ConnectedAt'),
                     ('tbPluggyConnection', 'LastUpdatedAt'),
                     ('tbPluggyConnection', 'ConsentExpiresAt'),
                     ('tbPluggyConnection', 'InvestmentAssetsLastAttemptAt'),
                     ('tbPluggyConnection', 'InvestmentAssetsLastSuccessAt'),
                     ('tbPluggyCredential', 'UpdatedAt'),
                     ('tbPluggyInvestmentAssetLink', 'RegisteredAt'),
                     ('tbPluggyInvestmentAssetSnapshot', 'FetchedAt'),
                     ('tbPluggyInvestmentAssetSnapshot', 'PositionDate'),
                     ('tbPluggyInvestmentAssetSnapshot', 'PurchaseDate'),
                     ('tbPluggyTransactionImport', 'RegisteredAt'))
    LOOP
        EXECUTE format(
            'ALTER TABLE public.%I ALTER COLUMN %I TYPE timestamp with time zone USING %I AT TIME ZONE ''UTC''',
            column_to_fix.table_name,
            column_to_fix.column_name,
            column_to_fix.column_name);
    END LOOP;
END
$migration$;

-- SQL Server datetime2 stores a calendar time without a timezone. pgloader
-- imports it as timestamptz; restore original DateTime calendar values.
DO $migration$
DECLARE
    column_to_fix record;
BEGIN
    FOR column_to_fix IN
        SELECT table_name, column_name
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name LIKE 'tb%'
          AND data_type = 'timestamp with time zone'
          AND (table_name, column_name) NOT IN (
              VALUES ('tbCarteira', 'CriadaEm'),
                     ('tbCarteira', 'AtualizadaEm'),
                     ('tbPluggyConnection', 'ConnectedAt'),
                     ('tbPluggyConnection', 'LastUpdatedAt'),
                     ('tbPluggyConnection', 'ConsentExpiresAt'),
                     ('tbPluggyConnection', 'InvestmentAssetsLastAttemptAt'),
                     ('tbPluggyConnection', 'InvestmentAssetsLastSuccessAt'),
                     ('tbPluggyCredential', 'UpdatedAt'),
                     ('tbPluggyInvestmentAssetLink', 'RegisteredAt'),
                     ('tbPluggyInvestmentAssetSnapshot', 'FetchedAt'),
                     ('tbPluggyInvestmentAssetSnapshot', 'PositionDate'),
                     ('tbPluggyInvestmentAssetSnapshot', 'PurchaseDate'),
                     ('tbPluggyTransactionImport', 'RegisteredAt'))
    LOOP
        EXECUTE format(
            'ALTER TABLE public.%I ALTER COLUMN %I TYPE timestamp without time zone USING %I AT TIME ZONE ''UTC''',
            column_to_fix.table_name,
            column_to_fix.column_name,
            column_to_fix.column_name);
    END LOOP;
END
$migration$;

-- The SQL Server rowversion was imported as hexadecimal text. The app uses
-- byte[] concurrency tokens, so store the bytes and generate a new token on
-- every update.
DO $migration$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'tbInvestimentoGrupoObjetivo'
          AND column_name = 'Versao'
          AND data_type = 'text'
    ) THEN
        ALTER TABLE public."tbInvestimentoGrupoObjetivo"
            ALTER COLUMN "Versao" TYPE bytea USING decode("Versao", 'hex');
    END IF;
END
$migration$;

ALTER TABLE public."tbInvestimentoGrupoObjetivo"
    ALTER COLUMN "Versao" SET DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex');

CREATE OR REPLACE FUNCTION public.yourmoney_refresh_group_version()
RETURNS trigger LANGUAGE plpgsql AS $function$
BEGIN
    NEW."Versao" := decode(replace(gen_random_uuid()::text, '-', ''), 'hex');
    RETURN NEW;
END
$function$;

DROP TRIGGER IF EXISTS yourmoney_refresh_group_version
    ON public."tbInvestimentoGrupoObjetivo";
CREATE TRIGGER yourmoney_refresh_group_version
    BEFORE UPDATE ON public."tbInvestimentoGrupoObjetivo"
    FOR EACH ROW EXECUTE FUNCTION public.yourmoney_refresh_group_version();

